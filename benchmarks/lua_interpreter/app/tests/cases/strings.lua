assert(err(string.sub, "x", 1.5) == "bad argument #2 to 'sub' (number has no integer representation)")
assert(("x"):rep(3) == "xxx" and ("%d"):format(7) == "7" and ("abc"):find("b") == 2)
-- string coercions in the string functions
assert(string.upper(12) == "12" and string.rep(1, 3) == "111")
-- find
assert(select(2, string.find("hello world", "wor")) == 9 and string.find("hello", "xyz") == nil)
local s, e = string.find("hello world", "o w"); assert(s == 5 and e == 7)
s, e = string.find("hello", "l+"); assert(s == 3 and e == 4)
s, e = string.find("hello", ""); assert(s == 1 and e == 0)
s, e = string.find("hello", "", 10); assert(s == nil)
s, e = string.find("hello", "", 6); assert(s == 6 and e == 5)
s, e = string.find("a.b", ".", 1, true); assert(s == 2 and e == 2)
s, e = string.find("a+b", "+", 1, true); assert(s == 2)
s, e = string.find("abcabc", "b", 3); assert(s == 5)
s, e = string.find("abcabc", "b", -2); assert(s == 5)
local f1, f2, c1, c2 = string.find("key=val", "(%w+)=(%w+)"); assert(f1 == 1 and f2 == 7 and c1 == "key" and c2 == "val")
assert(string.find("abc", "^b") == nil and string.find("abc", "^a") == 1 and string.find("abc", "c$") == 3 and string.find("abc", "b$") == nil)
assert(string.find("a$b", "$b") == 2 and string.find("a^b", "a^") == 1)
-- character classes
assert(string.match("abc123", "%a+") == "abc" and string.match("abc123", "%d+") == "123" and string.match("a b", "%s") == " ")
assert(string.match("Hello", "%u") == "H" and string.match("Hello", "%l+") == "ello" and string.match("a.b", "%p") == ".")
assert(string.match("a1_", "%w+") == "a1" and string.match("ff0g", "%x+") == "ff0" and string.match("a\1b", "%c") == "\1")
assert(string.match("a b", "%S+") == "a" and string.match("12ab", "%D+") == "ab" and string.match("ab12", "%A+") == "12")
assert(string.match("x-y", "[%w]+") == "x" and string.match("x-y", "[%-]") == "-" and string.match("abc", "[a-b]+") == "ab")
assert(string.match("abc", "[^a]+") == "bc" and string.match("a]b", "[]]") == "]" and string.match("a^b", "[%^]") == "^")
assert(string.match("abc", "[%a]+") == "abc" and string.match("a-", "[a%-]+") == "a-" and string.match("5", "[0-9]") == "5")
assert(string.match("hello", ".") == "h" and string.match("\0a", ".") == "\0" and string.match("a\nb", "a.b") == "a\nb")
-- quantifiers
assert(string.match("aaa", "a*") == "aaa" and string.match("aaa", "a-") == "" and string.match("aaa", "a+") == "aaa")
assert(string.match("aaab", "a-b") == "aaab" and string.match("b", "a?b") == "b" and string.match("ab", "a?b") == "ab")
assert(string.match("<a><b>", "<.->") == "<a>" and string.match("<a><b>", "<.*>") == "<a><b>")
assert(string.match("  x", "^%s*(.-)%s*$") == "x" and string.match("x  ", "^%s*(.-)%s*$") == "x")
-- captures
local k, v = string.match("from=world", "(%w+)=(%w+)"); assert(k == "from" and v == "world")
assert(string.match("abc", "()b()") == 2 and select(2, string.match("abc", "()b()")) == 3)
assert(string.match("hello", "(h)(e)(l)(l)(o)") == "h" and select('#', string.match("hello", "(h)(e)(l)(l)(o)")) == 5)
assert(string.match("abcabc", "(abc)%1") == "abc" and string.match("abcabd", "(abc)%1") == nil)
assert(string.match("say 'hi'", "(['\"])(.-)%1") == "'" and select(2, string.match("say 'hi'", "(['\"])(.-)%1")) == "hi")
assert(string.match("abc", "((a)(b))") == "ab" and select(2, string.match("abc", "((a)(b))")) == "a")
-- %b and %f
assert(string.match("f(a(b)c)d", "%b()") == "(a(b)c)" and string.match("x", "%b()") == nil and string.match("[[x]]", "%b[]") == "[[x]]")
assert(string.gsub("THE (quick) fox", "%f[%a]%a+", "W") == "W (W) W")
assert(string.find("THE (quick) fox", "%f[%a]%a+", 5) == 6)
assert(string.match("hello world", "%f[%w]%w+$") == "world" and string.find("abc", "%f[^%w]") == 4)
assert(select(2, string.gsub("a b  c", "%f[%S]", "|")) == 2)   -- no frontier at the start: "\0" is in %S
-- gmatch (manual examples)
