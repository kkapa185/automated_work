assert(("aBc"):upper() == "ABC" and ("aBc"):lower() == "abc" and ("abc"):reverse() == "cba" and (""):reverse() == "")
assert(("ab"):rep(3) == "ababab" and ("ab"):rep(3, "-") == "ab-ab-ab" and ("ab"):rep(0) == "" and ("ab"):rep(-1) == "" and ("ab"):rep(1, "-") == "ab")
assert(("abc"):byte() == 97 and select('#', ("abc"):byte(1, -1)) == 3 and ("abc"):byte(-1) == 99 and ("abc"):byte(10) == nil)
assert(select('#', ("abc"):byte(10)) == 0)
local b1, b2, b3 = ("abc"):byte(1, 3); assert(b1 == 97 and b2 == 98 and b3 == 99)
assert(string.char() == "" and string.char(72, 105) == "Hi" and string.char(0, 255) == "\0\255")
assert(err(string.char, 256) == "bad argument #1 to 'char' (value out of range)")
assert(err(string.rep, "x", 1e10) == "resulting string too large")
assert(#string.rep("x", 1000000) == 1000000 and #string.rep("ab", 1000, ",") == 2999)
assert(err(string.sub) == "bad argument #1 to 'sub' (string expected, got no value)")
assert(err(string.sub, {}, 1) == "bad argument #1 to 'sub' (string expected, got table)")
