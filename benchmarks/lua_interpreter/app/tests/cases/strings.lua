local function err(f, ...) local ok, e = pcall(f, ...); assert(not ok); return e end
-- basic functions
assert(("hello"):len() == 5 and #"" == 0 and ("a\0b"):len() == 3 and string.len(123) == 3)
assert(("hello"):sub(2, 4) == "ell" and ("hello"):sub(-3) == "llo" and ("hello"):sub(2) == "ello" and ("hello"):sub(0) == "hello")
assert(("hello"):sub(4, 2) == "" and ("hello"):sub(-100, 100) == "hello" and ("hello"):sub(6) == "" and ("hello"):sub(-2, -1) == "lo")
