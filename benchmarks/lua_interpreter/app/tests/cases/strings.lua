assert(#words == 4 and words[1] == "hello" and words[4] == "Lua")
local t = {}
for k, v in string.gmatch("from=world, to=Lua", "(%w+)=(%w+)") do t[k] = v end
assert(t.from == "world" and t.to == "Lua")
local cnt = 0; for _ in string.gmatch("abc", "") do cnt = cnt + 1 end; assert(cnt == 4)
local pos = {}; for p in string.gmatch("abc", "()") do pos[#pos + 1] = p end; assert(#pos == 4 and pos[4] == 4)
local it = string.gmatch("a1b2", "%d"); assert(it() == "1" and it() == "2" and it() == nil)
local g3 = {}; for w in string.gmatch("one two three", "%a+", 5) do g3[#g3 + 1] = w end; assert(#g3 == 2 and g3[1] == "two")
local gc = 0; for x in string.gmatch("^a^a", "^a") do gc = gc + 1 end; assert(gc == 2)   -- ^ is not an anchor in gmatch
-- gsub (manual examples)
assert(string.gsub("hello world", "(%w+)", "%1 %1") == "hello hello world world")
assert(string.gsub("hello world", "%w+", "%0 %0", 1) == "hello hello world")
assert(string.gsub("hello world from Lua", "(%w+)%s*(%w+)", "%2 %1") == "world hello Lua from")
local envt = {HOME = "/home/roberto", USER = "roberto"}
assert(string.gsub("home = $HOME, user = $USER", "%$(%w+)", function(n) return envt[n] end) == "home = /home/roberto, user = roberto")
assert(string.gsub("4+5 = $return 4+5$", "%$(.-)%$", function(s) return load(s)() end) == "4+5 = 9")
assert(string.gsub("$name-$version.tar.gz", "%$(%w+)", {name = "lua", version = "5.5"}) == "lua-5.5.tar.gz")
local r, n = string.gsub("abc", "%w", "%0%0"); assert(r == "aabbcc" and n == 3)
r, n = string.gsub("hello", "", "-"); assert(r == "-h-e-l-l-o-" and n == 6)
r, n = string.gsub("abc", "b", "%%"); assert(r == "a%c" and n == 1)
r, n = string.gsub("aaa", "a", "b", 2); assert(r == "bba" and n == 2)
r, n = string.gsub("aaa", "a", "b", 0); assert(r == "aaa" and n == 0)
r, n = string.gsub("abc", "^a", "x"); assert(r == "xbc" and n == 1)
r, n = string.gsub("aaa", "^a", "x"); assert(r == "xaa" and n == 1)
r, n = string.gsub("abc", "x*", "-"); assert(r == "-a-b-c-" and n == 4)
r, n = string.gsub("abc", "b", function() return false end); assert(r == "abc" and n == 1)
r, n = string.gsub("abc", "b", function() return nil end); assert(r == "abc")
