assert(10 % 3 == 1 and -10 % 3 == 2 and 10 % -3 == -2 and -10 % -3 == -1)
assert(5.5 // 2 == 2.0 and -5.5 // 2 == -3.0 and 5.5 % 2 == 1.5 and -5.5 % 2 == 0.5 and 5.5 % -2 == -0.5)
assert(7 // 0.0 == 1/0 and -7 // 0.0 == -1/0)
