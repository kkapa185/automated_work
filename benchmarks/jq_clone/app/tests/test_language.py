@pytest.mark.parametrize("prog,inp,msg", ERRORS, ids=[e[0][:40] for e in ERRORS])
def test_runtime_errors(prog, inp, msg):
    with pytest.raises(JQError) as ei:
        evaluate(prog, j(inp)[0])
    if msg is not None:
        assert ei.value.message() == msg


@pytest.mark.parametrize("prog", [
    "1 +", ".[", "{a:", "if 1 then 2", "foo", "foo(1)", "$nope", "break $x", "reduce . as $x", "1 as", ")",
    "def f: 1", ". as [$a, ] | 1", "\"abc", "@bogus", "{a b}", ". = ", "try", "[1,2",
])
def test_compile_errors(prog):
    with pytest.raises((JQSyntaxError, JQError)):
        evaluate(prog, None)


def test_lazy_generators_do_not_run_forever():
    assert evaluate("first(range(1000000000))") == [0]
    assert evaluate("[limit(3; repeat(1))]") == [[1, 1, 1]]
    assert evaluate("isempty(range(1000000000))") == [False]


def test_deep_recursion():
    assert evaluate("def f: if . >= 5000 then . else .+1 | f end; 0 | f") == [5000]
    assert evaluate("last(range(200000))") == [199999]
    assert evaluate("[recurse(if . < 20000 then .+1 else empty end)] | length", 0) == [20001]
